//! Compile in every committed render pack (`render_packs/<body>/`, `tools/render_packs.py`):
//! its description, collision proxies and `pack.json`, and each earlier description the asset
//! tree keeps that `pack.json` names (`superseded_descriptions`), as `files::REGISTERED`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let package = manifest.join("../..");
    let packs = package.join("render_packs");
    println!("cargo:rerun-if-changed={}", packs.display());
    let mut names: Vec<String> = std::fs::read_dir(&packs)
        .expect("render_packs")
        .filter_map(Result::ok)
        .filter(|entry| entry.path().join("pack.json").is_file())
        .filter(|entry| entry.path().join("collision.json").is_file())
        .map(|entry| entry.file_name().to_string_lossy().into_owned())
        .collect();
    names.sort();
    let mut out = String::from(
        "/// Every committed render pack, by name (generated by `build.rs`).\n\
         static REGISTERED: &[BodyFiles<'static>] = &[\n",
    );
    for name in &names {
        let dir = packs.join(name);
        let pack = dir.join("pack.json");
        for file in ["robot.urdf", "collision.json", "pack.json"] {
            println!("cargo:rerun-if-changed={}", dir.join(file).display());
        }
        let document: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(&pack).expect("pack.json"))
                .expect("pack.json parses");
        let superseded: Vec<PathBuf> = document["superseded_descriptions"]
            .as_array()
            .map(|paths| {
                paths
                    .iter()
                    .filter_map(serde_json::Value::as_str)
                    .map(|path| package.join("assets").join(path))
                    .collect()
            })
            .unwrap_or_default();
        for path in &superseded {
            assert!(path.is_file(), "{name}: {} is not kept", path.display());
            println!("cargo:rerun-if-changed={}", path.display());
        }
        let include = |path: &Path| format!("include_str!({:?})", path.display().to_string());
        writeln!(
            out,
            "    BodyFiles {{ embodiment: {name:?}, urdf: {}, collision: {}, pack: {}, superseded: &[{}] }},",
            include(&dir.join("robot.urdf")),
            include(&dir.join("collision.json")),
            include(&pack),
            superseded
                .iter()
                .map(|path| include(path))
                .collect::<Vec<_>>()
                .join(", "),
        )
        .expect("write");
    }
    out.push_str("];\n");
    let target = PathBuf::from(std::env::var("OUT_DIR").expect("out dir")).join("registered.rs");
    std::fs::write(target, out).expect("registered.rs");
}
